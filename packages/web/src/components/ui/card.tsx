  HTMLHeadingElement,
  React.HTMLAttributes<HTMLHeadingElement>
>(({ className, ...props }, ref) => (
  <h3
    ref={ref}
    className={cn(
      "text-sm font-semibold tracking-tight text-zinc-100 uppercase",
      className
    )}
    {...props}
  />
));
CardTitle.displayName = "CardTitle";

